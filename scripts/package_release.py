"""Create a compact ready-to-run ZIP (source + built site, no raw dataset/venvs)."""
import argparse
import hashlib
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--output', type=Path, required=True)
args = parser.parse_args()
if not (ROOT / 'frontend/dist/index.html').exists():
    raise SystemExit('Run npm ci and npm run build in frontend first.')
allowed = {'.github', 'backend', 'docs', 'examples', 'frontend', 'scripts', 'tests', 'training'}
excluded = {'.git', 'node_modules', '.venv', 'venv', '.export-venv', '__pycache__', '.pytest_cache', 'dataset', 'DuLieuGoc', '.cache', 'source-cache', 'runs'}
files = []
for p in ROOT.rglob('*'):
    rel = p.relative_to(ROOT)
    if not p.is_file() or any(part in excluded for part in rel.parts):
        continue
    if len(rel.parts) > 1 and rel.parts[0] not in allowed:
        continue
    if len(rel.parts) == 1 and p.name not in {'README.md','.gitignore','.gitattributes','CHAY-WEBSITE.cmd'}:
        continue
    if p.name == '.env' or (p.name.startswith('.env.') and p.name != '.env.example'):
        continue
    if str(rel).replace('\\','/').startswith('frontend/public/runtime/'):
        continue # generated by npm; ready-built runtime is already in dist
    if p.suffix in {'.pyc','.log'}:
        continue
    files.append(p)
args.output.parent.mkdir(parents=True, exist_ok=True)
with ZipFile(args.output, 'w', compression=ZIP_DEFLATED, compresslevel=6) as archive:
    for p in sorted(files):
        archive.write(p, 'TeaLeafAI/' + p.relative_to(ROOT).as_posix())
with ZipFile(args.output) as archive:
    if archive.testzip():
        raise SystemExit('ZIP integrity check failed.')
    names = archive.namelist()
    for needed in ['CHAY-WEBSITE.cmd', 'frontend/dist/index.html', 'frontend/dist/model/tea-leaf.onnx', 'frontend/dist/runtime/ort-wasm-simd-threaded.wasm', 'frontend/scripts/serve-dist.mjs']:
        assert 'TeaLeafAI/' + needed in names, needed
sha = hashlib.sha256(args.output.read_bytes()).hexdigest()
args.output.with_name('SHA256SUMS.txt').write_text(f'{sha}  {args.output.name}\n')
print(f'{args.output}: {len(files)} files, {args.output.stat().st_size / 1024**2:.1f} MiB; SHA256 {sha}')
